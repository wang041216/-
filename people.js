function element(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text) node.textContent = text;
  return node;
}

function buildingLink(person, text) {
  const link = element("a", "person-building-link", text);
  link.href = `./old-building.html?place=${person.buildingId}`;
  return link;
}

function renderCard(person) {
  const card = element("article", "person-card");
  const portrait = element("a", "person-card-image");
  portrait.href = `./people.html?person=${person.id}`;
  const image = document.createElement("img");
  image.src = person.image;
  image.alt = person.imageAlt;
  image.loading = "lazy";
  portrait.append(image);
  card.append(portrait);

  const body = element("div", "person-card-body");
  body.append(element("h2", "", person.name));
  body.append(element("p", "person-card-title", person.title));
  body.append(element("p", "person-card-summary", person.summary));
  body.append(buildingLink(person, `定位 ${person.building} →`));
  const open = element("a", "person-card-more", "阅读人物故事 ↗");
  open.href = `./people.html?person=${person.id}`;
  body.append(open);
  card.append(body);
  return card;
}

function renderPerson(person) {
  const detail = document.querySelector("#personDetail");
  detail.hidden = false;
  document.querySelector("#peopleOverview").hidden = true;
  document.querySelector("#personBreadcrumb").hidden = false;
  document.querySelector("#personBreadcrumb").textContent = `／ ${person.name}`;
  document.title = `${person.name} · 瓦檐载医魂`;

  const imageCard = element("figure", "person-detail-image");
  const image = document.createElement("img");
  image.src = person.image;
  image.alt = person.imageAlt;
  imageCard.append(image, element("figcaption", "", person.imageCaption));

  const copy = element("div", "person-detail-copy");
  copy.append(element("p", "eyebrow", `A PERSON · A PLACE · A STORY`));
  copy.append(element("h1", "", person.name));
  copy.append(element("p", "person-detail-title", person.title));
  copy.append(element("p", "person-detail-deck", person.summary));
  copy.append(element("h2", "", "人物简介"));
  copy.append(element("p", "", person.introduction));
  copy.append(element("h2", "", "老楼里的故事"));
  copy.append(element("p", "", person.story));
  copy.append(element("h2", "", "医学贡献"));
  copy.append(element("p", "", person.contribution));
  copy.append(element("h2", "", "与老楼的关联"));
  copy.append(element("p", "", person.relation));
  if (person.caveat) copy.append(element("aside", "person-caveat", person.caveat));
  copy.append(buildingLink(person, `在老楼地图定位 ${person.building} →`));

  const sources = element("div", "story-sources person-sources");
  person.sources.forEach(([label, href]) => {
    const link = element("a", "", label);
    link.href = href;
    link.target = "_blank";
    link.rel = "noreferrer";
    sources.append(link);
  });
  copy.append(sources);
  const back = element("a", "person-back-link", "← 返回人物总览");
  back.href = "./people.html";
  copy.append(back);

  detail.append(imageCard, copy);
}

const params = new URLSearchParams(window.location.search);
const selectedPerson = people.find((person) => person.id === params.get("person"));
const peopleGrid = document.querySelector("#peopleGrid");

if (selectedPerson) {
  renderPerson(selectedPerson);
} else {
  people.forEach((person) => peopleGrid.append(renderCard(person)));
}
